import assert from "node:assert/strict";
import { test } from "node:test";
import { detect } from "../src/detect.ts";

test("scripts and stylesheets are claimed by name", () => {
  assert.deepEqual(detect("src/a.tsx", "export const a = 1;\n"), {
    path: "src/a.tsx",
    role: "source",
  });
  assert.deepEqual(detect("src/a.css", "p { margin: 0 }\n"), { path: "src/a.css", role: "source" });
  assert.equal(detect("src/a.d.ts", "export type A = 1;\n"), undefined);
  assert.equal(detect("README.md", "# hi\n"), undefined);
  assert.equal(detect("node_modules/x/index.js", "module.exports = 1;\n"), undefined);
});

test("a generated file says so in its header, with the tool when named", () => {
  assert.deepEqual(
    detect("src/api.ts", "// Code generated by openapi-gen. DO NOT EDIT.\nexport {};\n"),
    {
      path: "src/api.ts",
      role: "generated",
      tool: "openapi-gen",
    },
  );
  assert.deepEqual(
    detect("src/b.ts", "/**\n * This file was auto-generated by tool-x.\n */\nexport {};\n"),
    {
      path: "src/b.ts",
      role: "generated",
      tool: "tool-x",
    },
  );
  assert.deepEqual(detect("src/c.ts", "/* @generated */\nexport {};\n"), {
    path: "src/c.ts",
    role: "generated",
  });
  assert.equal(
    detect("src/d.ts", "export const note = 'Code generated by hand';\n")?.role,
    "source",
  );
});

test("a minified bundle checked into the tree is build output, not claimed", () => {
  assert.equal(detect("vendor/lib.js", `${"var a=1;".repeat(1000)}\n`), undefined);
});
