package detect

import "testing"

func TestFile(t *testing.T) {
	cases := []struct {
		path, content string
		want          Claim
		ok            bool
	}{
		{"a/a.go", "// Package a does a.\npackage a\n", Claim{Path: "a/a.go", Role: RoleSource}, true},
		{"a/a_test.go", "package a_test\n", Claim{Path: "a/a_test.go", Role: RoleSource}, true},
		{"api/server.gen.go", "// Package api provides primitives.\n//\n// Code generated by oapi-codegen version v2.4.1 DO NOT EDIT.\npackage api\n",
			Claim{Path: "api/server.gen.go", Role: RoleGenerated}, true},
		{"a/b.go", "package a\n\n// Code generated by hand DO NOT EDIT.\n", Claim{Path: "a/b.go", Role: RoleSource}, true},
		{"a/notgo.go", "this is no Go file\n", Claim{}, false},
		{"a/testdata/x.go", "package x\n", Claim{}, false},
		{"vendor/x/x.go", "package x\n", Claim{}, false},
		{"vendor/modules.txt", "# x v1\n", Claim{Path: "vendor/modules.txt", Role: RoleLockfile}, true},
		{"svc/go.mod", "module x\n", Claim{Path: "svc/go.mod", Role: RoleManifest}, true},
		{"svc/go.sum", "", Claim{Path: "svc/go.sum", Role: RoleLockfile}, true},
		{"MODULE.bazel", "go_sdk.download(version = \"1.25.0\")\n", Claim{Path: "MODULE.bazel", Role: RoleDirective}, true},
		{"MODULE.bazel", "bazel_dep(name = \"rules_go\")\n", Claim{}, false},
		{".github/x.go", "package x\n", Claim{}, false},
	}

	for _, c := range cases {
		got, ok := File(c.path, []byte(c.content))
		if ok != c.ok || got != c.want {
			t.Errorf("%s: %+v %v, want %+v %v", c.path, got, ok, c.want, c.ok)
		}
	}
}
