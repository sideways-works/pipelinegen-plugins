const (
	RoleGenerated = "generated"
	// RoleDirective is a Go file with a go:generate line that runs
	// oapi-codegen: it names the contract and the generator's config.
	RoleDirective = "directive"
	// RoleContract is an OpenAPI document, as openapi-sbom detects one. Every
	// contract is read: its routes count for every operation.
	RoleContract = openapi.RoleContract
	// RoleSource is Go code the scans read. Any Go file can reach the document
	// through a wrapper declared elsewhere, so every Go file under the scanned
	// directories is one.
	RoleSource = "source"
	// RoleManifest is a go.mod, which gives the import path of the packages below
	// it.
	RoleManifest = "manifest"
)

var CandidatePatterns = append([]string{"**/*.go", "**/go.mod"}, openapi.CandidatePatterns...)

type Detection struct {
	Path string `json:"path"`
	Role string `json:"role"`
	// Generator is the module the header names, Version its version (a
	// generated file).
	Generator string `json:"generator,omitempty"`
	Version   string `json:"version,omitempty"`
	// Declarations are the generated declarations this plugin knows, as
	// the file holds them (a generated file).
	Declarations []string `json:"declarations,omitempty"`
	// Contract and Config are the paths a go:generate line names, from the
	// tree's root (a directive).
	Contract string `json:"contract,omitempty"`
	Config   string `json:"config,omitempty"`
	// Depends are the files a contract's refs point into (a contract).
	Depends []string `json:"depends,omitempty"`
	// Module is the module path a go.mod declares (a manifest).
	Module string `json:"module,omitempty"`
}

var header = regexp.MustCompile(`(?m)^// Code generated by (github\.com/(?:oapi-codegen|deepmap)/oapi-codegen(?:/v2)?) version (\S+) DO NOT EDIT\.$`)

var known = map[string]bool{
	"ServerInterfaceWrapper": true, "strictHandler": true,
	varSwaggerSpec: true, varRawSpec: true,
	"ServerInterface": true, "StrictServerInterface": true,
	"Handler": true, "HandlerFromMux": true, "HandlerFromMuxWithBaseURL": true, "HandlerWithOptions": true,
	"NewStrictHandler": true, "NewStrictHandlerWithOptions": true,
	"RegisterHandlers": true, "RegisterHandlersWithBaseURL": true,
}

// Detect claims the Go files oapi-codegen wrote or that run it, the other Go
// files under the scanned directories, go.mod files and contracts. Every
// answer is about one file and the config alone.
func Detect(tree string, paths []string, cfg Config) []Detection {
	var out []Detection

	for _, p := range paths {
		if d, ok := detectOne(tree, p, cfg); ok {
			out = append(out, d...)
		}
	}

	return out
}

func detectOne(tree, p string, cfg Config) ([]Detection, bool) {
	isGo := strings.HasSuffix(p, ".go")
	isMod := path.Base(p) == "go.mod"

	if !isGo && !isMod {
		found := openapi.Detect(tree, []string{p})
		out := make([]Detection, 0, len(found))

		for _, c := range found {
			out = append(out, Detection{Path: c.Path, Role: RoleContract, Depends: c.References})
		}

		return out, len(out) > 0
	}

	if unbuilt(p) {
		return nil, false
	}

	data, err := os.ReadFile(filepath.Join(tree, filepath.FromSlash(p))) //nolint:gosec // a candidate of the tree
	if err != nil {
		return nil, false
	}

	if isMod {
		mod := modulePath(data)

		return []Detection{{Path: p, Role: RoleManifest, Module: mod}}, mod != ""
	}

	if d, ok := detectGenerated(p, data); ok {
		return []Detection{d}, true
	}

	if d, ok := detectDirective(p, data); ok {
		return []Detection{d}, true
	}

	if cfg.scans(p) {
		return []Detection{{Path: p, Role: RoleSource}}, true
	}

	return nil, false
}

func unbuilt(p string) bool {
	parts := strings.Split(path.Dir(p), "/")

	return slices.ContainsFunc(parts, func(n string) bool {
		return n == "vendor" || n == "node_modules" || n == "testdata" ||
			(n != "." && (strings.HasPrefix(n, ".") || strings.HasPrefix(n, "_")))
	})
}

func (c Config) scans(p string) bool {
	if len(c.Scan) == 0 {
		return true
	}

	dirs := slices.Clone(c.Scan)
	for _, d := range c.Documents {
		if d.Go != nil {
			dirs = append(dirs, d.Go.Handlers...)
		}
	}

	return under(dirs, p)
}

func under(dirs []string, p string) bool {
	if len(dirs) == 0 {
		return true
	}

	return slices.ContainsFunc(dirs, func(d string) bool {
		d = path.Clean(d)

		return d == "." || strings.HasPrefix(p, d+"/")
	})
}

func detectGenerated(p string, data []byte) (Detection, bool) {
	// The header comes before the package clause.
	head, _, _ := bytes.Cut(data, []byte("\npackage "))

	m := header.FindSubmatch(head)
	if m == nil {
		return Detection{}, false
	}

	d := Detection{Path: p, Role: RoleGenerated, Generator: string(m[1]), Version: string(m[2])}

	f, err := parser.ParseFile(token.NewFileSet(), p, data, parser.SkipObjectResolution)
	if err != nil {
		return d, true
	}

	seen := map[string]bool{}

	for _, decl := range f.Decls {
		for _, n := range topNames(decl) {
			if known[n] && !seen[n] {
				seen[n] = true
				d.Declarations = append(d.Declarations, n)
			}
		}
	}

	slices.Sort(d.Declarations)

	return d, true
}

// topNames are a declaration's names; a method counts by its receiver's
// type, which is what tells a server wrapper from a strict handler.
func topNames(decl ast.Decl) []string {
	switch d := decl.(type) {
	case *ast.FuncDecl:
		if d.Recv != nil && len(d.Recv.List) > 0 {
			return []string{recvName(d.Recv.List[0].Type)}
		}

		return []string{d.Name.Name}
	case *ast.GenDecl:
		var out []string

		for _, s := range d.Specs {
			switch x := s.(type) {
			case *ast.TypeSpec:
				out = append(out, x.Name.Name)
			case *ast.ValueSpec:
				for _, n := range x.Names {
					out = append(out, n.Name)
				}
			}
		}

		return out
	default:
		return nil
	}
}

// detectDirective reads go:generate lines that run oapi-codegen, however
// spelled, and takes the contract and the config file.
func detectDirective(p string, data []byte) (Detection, bool) {
	if !bytes.Contains(data, []byte("oapi-codegen")) {
		return Detection{}, false
	}

	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())

		rest, ok := strings.CutPrefix(line, "//go:generate ")
		if !ok || !strings.Contains(rest, "oapi-codegen") {
			continue
		}

		contract, config := directiveArgs(strings.Fields(rest))
		if contract == "" {
			continue
		}

		dir := path.Dir(p)
		d := Detection{Path: p, Role: RoleDirective, Contract: path.Clean(path.Join(dir, contract))}

		if config != "" {
			d.Config = path.Clean(path.Join(dir, config))
		}

		return d, true
	}

	return Detection{}, false
}

var flagsWithValue = map[string]bool{
	"config": true, "o": true, "package": true, "generate": true, "include-tags": true, "exclude-tags": true,
	"include-operation-ids": true, "exclude-operation-ids": true, "templates": true, "import-mapping": true,
	"exclude-schemas": true, "response-type-suffix": true, "alias-types": true, "initialism-overrides": true,
}

func directiveArgs(fields []string) (contract, config string) {
	i := slices.IndexFunc(fields, func(f string) bool { return strings.Contains(f, "oapi-codegen") })
	if i < 0 {
		return "", ""
	}

	for j := i + 1; j < len(fields); j++ {
		f := fields[j]

		if !strings.HasPrefix(f, "-") {
			contract = f

			continue
		}

		name, value, hasValue := strings.Cut(strings.TrimLeft(f, "-"), "=")
		if !hasValue && flagsWithValue[name] && j+1 < len(fields) {
			j++
			value = fields[j]
		}

		if name == "config" {
			config = value
		}
	}

	return contract, config
}

func goCandidates(tree string) ([]string, error) {
	var out []string

	err := walkGoFiles(tree, ".", func(rel string) { out = append(out, rel) })

	return out, err
}

// walkGoFiles lists the Go files under dir, tests included: a directive can
// sit in any file.
func walkGoFiles(tree, dir string, fn func(rel string)) error {
	root := filepath.Join(tree, filepath.FromSlash(dir))

	err := filepath.WalkDir(root, func(p string, e os.DirEntry, err error) error {
		if err != nil {
			return err
		}

		if e.IsDir() {
			n := e.Name()
			if p != root && (n == "vendor" || n == "node_modules" || n == "testdata" || strings.HasPrefix(n, ".") || strings.HasPrefix(n, "_")) {
				return filepath.SkipDir
			}

			return nil
		}

		if strings.HasSuffix(p, ".go") || e.Name() == "go.mod" {
			rel, err := filepath.Rel(tree, p)
			if err != nil {
				return err //nolint:wrapcheck // wrapped below
			}

			fn(filepath.ToSlash(rel))
		}

		return nil
	})
	if err != nil {
		return fmt.Errorf("walk %s: %w", dir, err)
	}

	return nil
}

// withContracts adds the contracts no generated package serves: their routes
// count for every operation.
func withContracts(docs []Document, contracts []string) []Document {
	slices.Sort(contracts)

	for _, c := range contracts {
		if !slices.ContainsFunc(docs, func(d Document) bool { return d.Path == c }) {
			var doc Document

			doc.Path = c
			docs = append(docs, doc)
		}
	}

	return docs
}

// fromDetections pairs each generated package with the contract a generate
// directive in its directory names. A package with no such line is returned
// apart.
func fromDetections(found []Detection) (docs []Document, unknown []Detection) {
	directives := map[string]Detection{}

	for _, d := range found {
		if d.Role == RoleDirective {
			directives[path.Dir(d.Path)] = d
		}
	}

	byPkg := map[string]*Document{}

	var (
		order     []string
		contracts []string
	)

	for _, d := range found {
		if d.Role == RoleContract {
			contracts = append(contracts, d.Path)
		}

		if d.Role != RoleGenerated {
			continue
		}

		dir := path.Dir(d.Path)

		dv, ok := directives[dir]
		if !ok {
			unknown = append(unknown, d)

			continue
		}

		doc, ok := byPkg[dir]
		if !ok {
			doc = &Document{Go: &GoConfig{Package: dir, NoWrapper: true, SpecVars: []string{}, Generator: d.Generator, GeneratorConfig: dv.Config}}
			doc.Path = dv.Contract
			byPkg[dir] = doc
			order = append(order, dir)
		}

		g := doc.Go

		for _, n := range d.Declarations {
			switch n {
			case "ServerInterfaceWrapper":
				g.NoWrapper = false
			case "strictHandler":
				g.Strict = true
			case varSwaggerSpec, varRawSpec:
				g.SpecVars = append(g.SpecVars, n)
			}

			g.Declarations = append(g.Declarations, n)
		}
	}

	slices.Sort(order)

	for _, dir := range order {
		docs = append(docs, *byPkg[dir])
	}

	return withContracts(docs, contracts), unknown
}
