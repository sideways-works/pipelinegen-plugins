import assert from "node:assert/strict";
import { test } from "node:test";
import { buildOf, detect } from "../src/builds.ts";

const none = () => false;

test("a bundler config is claimed when it imports the bundler", () => {
  assert.deepEqual(detect("web/vite.config.ts", 'import { defineConfig } from "vite";\n'), {
    path: "web/vite.config.ts",
    role: "directive",
    tool: "vite",
  });
  assert.deepEqual(detect("web/vite.config.ts", "export default {};\n"), {
    path: "web/vite.config.ts",
    role: "source",
  });
  assert.equal(
    detect("web/other.config.ts", 'import { defineConfig } from "vite";\n')?.role,
    "source",
  );
});

test("defaults: the config's directory, the root path, dist and public", () => {
  const b = buildOf(
    "web/vite.config.ts",
    'import { defineConfig } from "vite";\nexport default defineConfig({});\n',
    (p) => p === "web/index.html",
  );
  assert.deepEqual(b, {
    config: "web/vite.config.ts",
    dist: "web/dist",
    base: "/",
    public: "web/public",
    html: "web/index.html",
    unknown: [],
  });
});

test("settings written as text are read, from a function config too", () => {
  const b = buildOf(
    "apps/a/vite.config.ts",
    `import { defineConfig } from "vite";
const config = { root: "client", base: "/app", publicDir: "static", build: { outDir: "../out" } };
export default defineConfig(({ mode }) => config);
`,
    none,
  );
  assert.deepEqual(b, {
    config: "apps/a/vite.config.ts",
    dist: "apps/a/out",
    base: "/app/",
    public: "apps/a/client/static",
    unknown: [],
  });
});

test("settings computed at run time are named, so observe can say what it couldn't find", () => {
  const b = buildOf(
    "vite.config.ts",
    'import { defineConfig } from "vite";\nexport default defineConfig({ base: process.env.BASE, build: { outDir: dir() } });\n',
    none,
  );
  assert.deepEqual(b.unknown, ["base", "build.outDir"]);
  assert.equal(b.base, "/");
});

test("a full URL as base serves the build under its path, from its origin", () => {
  const b = buildOf(
    "vite.config.ts",
    'import { defineConfig } from "vite";\nexport default defineConfig({ base: "https://cdn.example/assets/v2/" });\n',
    none,
  );
  assert.equal(b.base, "/assets/v2/");
  assert.equal(b.origin, "https://cdn.example");
  const path = buildOf(
    "vite.config.ts",
    'import { defineConfig } from "vite";\nexport default defineConfig({ base: "/app/" });\n',
    none,
  );
  assert.equal(path.origin, undefined);
});

test("every tsconfig and package.json is claimed: their presence changes where imports lead", () => {
  const paths = '{ "compilerOptions": { "paths": { "@x/*": ["x/*"] } } }';
  assert.equal(detect("tsconfig.json", paths)?.role, "directive");
  assert.deepEqual(detect("a/tsconfig.json", '{ "extends": "../tsconfig.base" }'), {
    path: "a/tsconfig.json",
    role: "directive",
    tool: "typescript",
    depends: ["tsconfig.base.json"],
  });
  assert.deepEqual(detect("a/tsconfig.json", '{ "compilerOptions": { "strict": true } }'), {
    path: "a/tsconfig.json",
    role: "directive",
    tool: "typescript",
  });
  const pkg = '{ "name": "@x/m", "exports": "./src/index.ts" }';
  assert.equal(detect("pkgs/m/package.json", pkg)?.role, "manifest");
  assert.equal(detect("package.json", "{}")?.role, "manifest");
  assert.equal(detect("node_modules/x/package.json", pkg), undefined);
});

test("scripts and styles are claimed as the sbom claims them, and assets an import can name", () => {
  assert.deepEqual(detect("src/a.tsx", "export const a = 1;\n"), {
    path: "src/a.tsx",
    role: "source",
    recorded: true,
  });
  assert.deepEqual(detect("src/a.css", "a {}\n"), { path: "src/a.css", role: "source" });
  assert.equal(detect("src/a.d.ts", "export {};\n"), undefined);
  assert.deepEqual(
    detect("src/api.ts", "// Code generated by gen. DO NOT EDIT.\nexport const a = 1;\n"),
    {
      path: "src/api.ts",
      role: "generated",
      tool: "gen",
      recorded: true,
    },
  );
  assert.equal(detect(`dist/app.js`, `${"x".repeat(6000)}\n`), undefined);
  for (const f of ["src/logo.svg", "src/data.json", "public/font.woff2", "index.html"])
    assert.equal(detect(f, "")?.role, "asset", f);
  assert.equal(detect("src/data.yaml", "a: 1\n"), undefined);
});

test("a claim says when a recording can hold the file's units", () => {
  const recorded = (path: string, text = "export const a = 1;\n") =>
    detect(path, text)?.recorded === true;
  assert.ok(recorded("src/t.ts", "export interface A {\n  a: number;\n}\nexport const B = 1;\n"));
  assert.ok(recorded("src/t.ts", "export type A = number;\nexport default function f() {}\n"));
  for (const f of [
    "src/a.ts",
    "src/a.tsx",
    "src/a.js",
    "src/a.jsx",
    "src/a.mjs",
    "src/a.cjs",
    "src/a.mts",
    "e2e/shop.spec.ts",
  ])
    assert.ok(recorded(f), f);
  for (const f of ["web/public/logo.svg", "public/robots.txt", "public/font.woff2"])
    if (detect(f, "")) assert.ok(recorded(f, ""), f);
  for (const [f, text] of [
    ["playwright.config.ts", "export default {};\n"],
    [
      "src/types.ts",
      "// shapes\nexport interface Line {\n  cents: number;\n}\nexport type Id = string;\nimport type { X } from './x';\n",
    ],
    ["src/a.css", "a {}\n"],
    ["src/logo.svg", ""],
    ["src/data.json", "{}"],
    ["index.html", ""],
    ["package.json", "{}"],
    ["tsconfig.json", "{}"],
    ["web/vite.config.ts", 'import { defineConfig } from "vite";\n'],
    [
      "tools/vite/brand.ts",
      'import type { Plugin } from "vite";\nexport function brand(): Plugin { return { name: "b" }; }\n',
    ],
    ["tools/build/copy.ts", 'import { build } from "esbuild";\n'],
  ] as [string, string][])
    assert.ok(!recorded(f, text), f);
});

test("a script of types alone is claimed as erased, and nothing that emits code is", () => {
  const erased = (text: string, path = "src/t.ts") => detect(path, text)?.erased === true;
  for (const t of [
    "export interface Line {\n  cents: number;\n}\n",
    "// shapes\nexport type Id = string;\ntype Pair<A> = [A, A];\n",
    'import type { X } from "./x";\nimport type Y from "./y";\nexport type { X };\nexport type * from "./z";\nexport interface Z extends X {}\n',
    "declare type A = number;\nexport {};\n",
  ])
    assert.ok(erased(t), t);
  for (const t of [
    "export enum Color {\n  Red,\n}\n",
    "export const enum Color {\n  Red,\n}\n",
    "declare enum Color {\n  Red,\n}\n",
    "export namespace N {\n  export const a = 1;\n}\n",
    'declare module "x" {\n  interface Y {}\n}\nexport {};\n',
    "declare global {\n  interface Window { x: number }\n}\nexport {};\n",
    '/// <reference path="./globals.d.ts" />\nexport interface A {}\n',
    '/// <reference types="vite/client" />\n',
    'import "./x";\nexport type A = number;\n',
    'import type from "./x";\nexport type A = number;\n',
    "export default interface A {}\nexport default 1;\n",
    "export = {};\n",
    "export type A = number;\nconst type = 1;\n",
    "type = 5;\n",
  ])
    assert.ok(!erased(t), t);
  const d = detect("src/types.ts", "export interface A {}\n");
  assert.equal(d?.recorded, undefined);
  assert.equal(d?.erased, true);
  assert.equal(detect("src/a.d.ts", "export interface A {}\n"), undefined);
  assert.equal(
    detect("src/api.ts", "// Code generated by gen. DO NOT EDIT.\nexport interface Order {}\n")
      ?.erased,
    true,
  );
});
