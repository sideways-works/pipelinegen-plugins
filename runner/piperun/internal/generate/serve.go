package generate

import (
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"path/filepath"

	"github.com/sideways-works/pipelinegen/plugin"
	"go.yaml.in/yaml/v3"
)

// Version is the plugin's version, set by the release build.
var Version = "dev"

// FileName is the pipeline's file in the call's work directory, as piperun reads it at a repository's
// root.
const FileName = "piperun.yaml"

// capOwnSettings is pipelinegen's plugin.CapOwnSettings: the runner takes its settings from its own
// config block, so a config for it needs no concourse section.
const capOwnSettings = "own-settings"

// Serve answers pipelinegen's calls.
func Serve(args []string, stdin io.Reader, stdout, stderr io.Writer) int {
	return plugin.Serve(args, stdin, stdout, stderr, map[string]plugin.Handler{
		plugin.CallDescribe: func([]byte) (any, error) { return describe(), nil },
		plugin.CallPipeline: pipeline,
	})
}

func describe() plugin.Description {
	return plugin.Description{
		Protocol: plugin.Protocol, Kind: plugin.KindRunner, Name: "piperun-runner", Version: Version,
		// placement is each suite's needs rule; steps run by the suites' drivers
		Capabilities: []string{plugin.CallPipeline, capOwnSettings, plugin.CapPlacement, plugin.CapSteps, plugin.CapContinuous},
		// piperun keeps a cache per repository and trust, shared by every job that mounts it
		CacheScopes: map[string]string{planCache: plugin.ScopePipeline},
	}
}

func pipeline(in []byte) (any, error) {
	var req plugin.PipelineRequest
	if err := json.Unmarshal(in, &req); err != nil {
		return nil, fmt.Errorf("%w: request: %w", ErrSpec, err)
	}

	set, err := ReadSettings(req.Config)
	if err != nil {
		return nil, err
	}

	f, notices, err := Generate(req.Spec, set)
	if err != nil {
		return nil, err
	}

	text, err := Text(f)
	if err != nil {
		return nil, err
	}

	if err := os.WriteFile(filepath.Join(req.Work, FileName), text, 0o600); err != nil {
		return nil, fmt.Errorf("%w: write: %w", ErrSpec, err)
	}

	return plugin.PipelineAnswer{Files: []string{FileName}, Notices: notices}, nil
}

// Text is the file's bytes, headed by where it came from.
func Text(f File) ([]byte, error) {
	var b bytes.Buffer

	b.WriteString("# Generated by piperun-runner " + Version + " from pipelinegen.yaml (pipelinegen pipeline). Do not edit.\n")

	enc := yaml.NewEncoder(&b)
	enc.SetIndent(2)

	if err := enc.Encode(f); err != nil {
		return nil, fmt.Errorf("%w: %w", ErrSpec, err)
	}

	if err := enc.Close(); err != nil {
		return nil, fmt.Errorf("%w: %w", ErrSpec, err)
	}

	return b.Bytes(), nil
}
